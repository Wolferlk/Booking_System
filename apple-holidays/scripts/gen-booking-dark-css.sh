#!/usr/bin/env bash
# Generates src/app/dashboard/bookings/[ref]/booking-dark.generated.css
#
# The booking detail page has a per-user light / dark switch. Rather than add a
# `dark:` twin to every class in the page and its ~50 panels, the page puts
# `bk-dark` on <html> while it is open and this file remaps the light Tailwind
# palette (bg-white, text-slate-700, bg-amber-50, border-emerald-200, …) to dark
# equivalents under that one class. Nothing applies unless `html.bk-dark` is set,
# so every other page is untouched.
#
# Islands that are already dark (the sidebar, `bg-slate-900` cards, the journey
# map's own dark skin) opt out with `data-theme-keep` or are skipped by colour.
#
# Re-run after changing the palette:   bash scripts/gen-booking-dark-css.sh
set -euo pipefail
cd "$(dirname "$0")/.."
OUT='src/app/dashboard/bookings/[ref]/booking-dark.generated.css'

S='html.bk-dark'
# Not inside, and not itself, an island that is already dark.
K=':not(:is([data-theme-keep],.bg-slate-900,.bg-slate-950,.bg-gray-900,.bg-black) *):not([data-theme-keep])'

{
echo '/* GENERATED by scripts/gen-booking-dark-css.sh — do not edit by hand. */'

# rule <class-list (comma separated, escaped)> <declarations> [pseudo]
rule() { printf '%s :is(%s)%s%s{%s}\n' "$S" "$1" "${3:-}" "$K" "$2"; }

# ── Neutrals (slate + gray share one ramp) ────────────────────────────────
nb() { # bg shade -> value
  local sh=$1 v=$2
  rule ".bg-slate-$sh,.bg-gray-$sh" "background-color:$v"
}
rule '.bg-white' 'background-color:var(--bk-surface)'
nb 50  'var(--bk-sunken)'
nb 100 'var(--bk-raised)'
nb 200 'var(--bk-raised-2)'
nb 300 '#3a475e'
for op in 5 10 20 30 40 50 60 70 75 80 85 88 90 95 97; do
  rule ".bg-white\\/$op"     "background-color:rgb(17 26 44 / ${op}%)"
  rule ".bg-slate-50\\/$op,.bg-gray-50\\/$op"   "background-color:rgb(11 18 32 / ${op}%)"
  rule ".bg-slate-100\\/$op,.bg-gray-100\\/$op" "background-color:rgb(26 36 54 / ${op}%)"
  rule ".bg-slate-200\\/$op,.bg-gray-200\\/$op" "background-color:rgb(36 48 71 / ${op}%)"
done
rule '.hover\:bg-white,.hover\:bg-slate-50,.hover\:bg-gray-50' 'background-color:var(--bk-hover)' ':hover'
rule '.hover\:bg-slate-100,.hover\:bg-gray-100' 'background-color:var(--bk-raised)' ':hover'
rule '.hover\:bg-slate-200,.hover\:bg-gray-200' 'background-color:var(--bk-raised-2)' ':hover'
rule '.hover\:bg-slate-50\/50,.hover\:bg-slate-50\/60,.hover\:bg-slate-50\/70,.hover\:bg-slate-50\/80' 'background-color:var(--bk-hover)' ':hover'

nt() { rule ".text-slate-$1,.text-gray-$1" "color:$2"; rule ".hover\\:text-slate-$1,.hover\\:text-gray-$1" "color:$2" ':hover'; }
nt 950 '#f8fafc'; nt 900 '#f1f5f9'; nt 800 '#e2e8f0'; nt 700 '#cbd5e1'; nt 600 '#aab6c8'
nt 500 '#8d9bb0'; nt 400 '#77869e'; nt 300 '#5b6a82'; nt 200 '#44526a'; nt 100 '#334155'
rule '.text-black' 'color:#f8fafc'
rule '.placeholder\:text-slate-400,.placeholder\:text-slate-300' 'color:#5b6a82' '::placeholder'

nbd() {
  rule ".border-slate-$1,.border-gray-$1" "border-color:$2"
  rule ".divide-slate-$1>:not([hidden])~:not([hidden]),.divide-gray-$1>:not([hidden])~:not([hidden])" "border-color:$2"
  rule ".ring-slate-$1,.ring-gray-$1" "--tw-ring-color:$2"
  rule ".hover\\:border-slate-$1,.hover\\:border-gray-$1" "border-color:$2" ':hover'
}
nbd 50 '#161f31'; nbd 100 '#1b2538'; nbd 200 '#243047'; nbd 300 '#2f3c55'; nbd 400 '#445069'
for op in 40 50 60 70 80; do
  rule ".border-slate-100\\/$op,.border-slate-200\\/$op,.border-slate-300\\/$op" "border-color:rgb(47 60 85 / ${op}%)"
done
rule '.border-white' 'border-color:var(--bk-surface)'
rule '.ring-white' '--tw-ring-color:var(--bk-surface)'
rule '.ring-slate-900\/5,.ring-slate-900\/10,.ring-black\/5' '--tw-ring-color:rgb(255 255 255 / 8%)'

# Gradients: only the stop that a class owns is swapped, so `from-x to-white`
# still composes the same way it does in light mode.
gfrom() { rule "$1" "--tw-gradient-from:$2 var(--tw-gradient-from-position)"; }
gvia()  { rule "$1" "--tw-gradient-stops:var(--tw-gradient-from), $2 var(--tw-gradient-via-position), var(--tw-gradient-to)"; }
gto()   { rule "$1" "--tw-gradient-to:$2 var(--tw-gradient-to-position)"; }
gfrom '.from-white' 'var(--bk-surface)';          gvia '.via-white' 'var(--bk-surface)';     gto '.to-white' 'var(--bk-surface)'
gfrom '.from-slate-50,.from-gray-50' 'var(--bk-sunken)';   gvia '.via-slate-50' 'var(--bk-sunken)';  gto '.to-slate-50,.to-gray-50' 'var(--bk-sunken)'
gfrom '.from-slate-100' 'var(--bk-raised)';       gvia '.via-slate-100' 'var(--bk-raised)'; gto '.to-slate-100' 'var(--bk-raised)'
gfrom '.from-slate-200' 'var(--bk-raised-2)';     gto '.to-slate-200' 'var(--bk-raised-2)'
for op in 50 60 70 80 90; do gto ".to-white\\/$op" "rgb(17 26 44 / ${op}%)"; gfrom ".from-white\\/$op" "rgb(17 26 44 / ${op}%)"; done

# ── Colour families ───────────────────────────────────────────────────────
# name  rgb-of-500       200      300      400
while read -r C R G B L2 L3 L4; do
  [ -z "$C" ] && continue
  c="$R $G $B"
  rule ".bg-$C-50"  "background-color:rgb($c / 10%)"
  rule ".bg-$C-100" "background-color:rgb($c / 16%)"
  rule ".bg-$C-200" "background-color:rgb($c / 24%)"
  for op in 30 40 50 60 70 80 90; do
    rule ".bg-$C-50\\/$op"  "background-color:rgb($c / $(( 10 * op / 100 + 3 ))%)"
    rule ".bg-$C-100\\/$op" "background-color:rgb($c / $(( 16 * op / 100 + 3 ))%)"
  done
  rule ".hover\\:bg-$C-50"  "background-color:rgb($c / 16%)" ':hover'
  rule ".hover\\:bg-$C-100" "background-color:rgb($c / 22%)" ':hover'
  rule ".hover\\:bg-$C-200" "background-color:rgb($c / 30%)" ':hover'

  rule ".text-$C-600,.hover\\:text-$C-600:hover" "color:$L4"
  rule ".text-$C-700,.hover\\:text-$C-700:hover" "color:$L3"
  rule ".text-$C-800,.text-$C-900,.text-$C-950" "color:$L2"
  for op in 60 70 80 90; do rule ".text-$C-800\\/$op,.text-$C-900\\/$op,.text-$C-700\\/$op" "color:$L3"; done

  rule ".border-$C-50,.border-$C-100" "border-color:rgb($c / 22%)"
  rule ".border-$C-200" "border-color:rgb($c / 32%)"
  rule ".border-$C-300" "border-color:rgb($c / 45%)"
  for op in 40 50 60 70 80; do rule ".border-$C-100\\/$op,.border-$C-200\\/$op,.border-$C-300\\/$op" "border-color:rgb($c / 28%)"; done
  rule ".hover\\:border-$C-200,.hover\\:border-$C-300" "border-color:rgb($c / 50%)" ':hover'
  rule ".divide-$C-100>:not([hidden])~:not([hidden]),.divide-$C-200>:not([hidden])~:not([hidden])" "border-color:rgb($c / 22%)"
  rule ".ring-$C-50,.ring-$C-100" "--tw-ring-color:rgb($c / 22%)"
  rule ".ring-$C-200" "--tw-ring-color:rgb($c / 32%)"

  gfrom ".from-$C-50"  "rgb($c / 12%)"
  gfrom ".from-$C-100" "rgb($c / 18%)"
  gvia  ".via-$C-50"   "rgb($c / 10%)"
  gvia  ".via-$C-100"  "rgb($c / 16%)"
  gto   ".to-$C-50"    "rgb($c / 8%)"
  gto   ".to-$C-100"   "rgb($c / 14%)"
  # Stops with an opacity (`from-amber-50/70`) — left light, they paint a
  # pastel slab across a dark card.
  for op in 30 40 50 60 70 80 90; do
    gfrom ".from-$C-50\\/$op,.from-$C-100\\/$op" "rgb($c / $(( 12 * op / 100 + 2 ))%)"
    gvia  ".via-$C-50\\/$op,.via-$C-100\\/$op"   "rgb($c / $(( 10 * op / 100 + 2 ))%)"
    gto   ".to-$C-50\\/$op,.to-$C-100\\/$op"     "rgb($c / $(( 8 * op / 100 + 2 ))%)"
  done
  # Mid-tone stops (glow borders, accent rails) — dimmed, not dropped.
  gfrom ".from-$C-200" "rgb($c / 38%)"; gvia ".via-$C-200" "rgb($c / 30%)"; gto ".to-$C-200" "rgb($c / 30%)"
  gfrom ".from-$C-300" "rgb($c / 55%)"; gvia ".via-$C-300" "rgb($c / 45%)"; gto ".to-$C-300" "rgb($c / 45%)"
done <<'PAL'
red     239 68 68    #fecaca #fca5a5 #f87171
rose    244 63 94    #fecdd3 #fda4af #fb7185
orange  249 115 22   #fed7aa #fdba74 #fb923c
amber   245 158 11   #fde68a #fcd34d #fbbf24
yellow  234 179 8    #fef08a #fde047 #facc15
brand   234 179 8    #fef08a #fde047 #facc15
lime    132 204 22   #d9f99d #bef264 #a3e635
green   34 197 94    #bbf7d0 #86efac #4ade80
emerald 16 185 129   #a7f3d0 #6ee7b7 #34d399
teal    20 184 166   #99f6e4 #5eead4 #2dd4bf
cyan    6 182 212    #a5f3fc #67e8f9 #22d3ee
sky     14 165 233   #bae6fd #7dd3fc #38bdf8
blue    59 130 246   #bfdbfe #93c5fd #60a5fa
indigo  99 102 241   #c7d2fe #a5b4fc #818cf8
